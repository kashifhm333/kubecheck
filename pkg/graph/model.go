package graph

import (
	"fmt"

	"github.com/kubecheck/kubecheck/pkg/inventory"
	"github.com/kubecheck/kubecheck/pkg/nir"
)

// EdgeType identifies the semantic nature of a cross-resource relationship per CROSS-RES-001.
type EdgeType string

const (
	EdgeOwnerReference           EdgeType = "OwnerReference"
	EdgeWorkloadSelectorMatch    EdgeType = "WorkloadSelectorMatch"
	EdgeServiceSelectorMatch     EdgeType = "ServiceSelectorMatch"
	EdgeNetworkPolicySelector    EdgeType = "NetworkPolicySelectorMatch"
	EdgePDBSelectorMatch         EdgeType = "PDBSelectorMatch"
	EdgeConfigMapRef             EdgeType = "ConfigMapRef"
	EdgeSecretRef                EdgeType = "SecretRef"
	EdgeServiceAccountRef        EdgeType = "ServiceAccountRef"
	EdgePVCRef                   EdgeType = "PVCRef"
	EdgeRoleRef                  EdgeType = "RoleRef"
	EdgeSubjectRef               EdgeType = "SubjectRef"
	EdgeIngressBackendServiceRef EdgeType = "IngressBackendServiceRef"
)

// ResolutionStatus classifies the resolution state of a relationship edge.
type ResolutionStatus string

const (
	StatusResolved   ResolutionStatus = "resolved"   // Target is admitted in the input set
	StatusUnresolved ResolutionStatus = "unresolved" // Target is not in the input set (may exist in cluster)
	StatusExternal   ResolutionStatus = "external"   // Target is intentionally external
	StatusGenerated  ResolutionStatus = "generated"  // Target is generated by a controller
)

// EdgeTargetHint contains structural metadata identifying the desired target of an edge.
type EdgeTargetHint struct {
	Group     string            `json:"group,omitempty"`
	Kind      string            `json:"kind"`
	Namespace string            `json:"namespace,omitempty"`
	Name      string            `json:"name,omitempty"`
	Selector  map[string]string `json:"selector,omitempty"`
}

func (h EdgeTargetHint) String() string {
	if len(h.Selector) > 0 {
		return fmt.Sprintf("%s in %s matching selector %v", h.Kind, h.Namespace, h.Selector)
	}
	if h.Group != "" {
		return fmt.Sprintf("%s.%s/%s/%s", h.Kind, h.Group, h.Namespace, h.Name)
	}
	if h.Namespace != "" {
		return fmt.Sprintf("%s/%s/%s", h.Kind, h.Namespace, h.Name)
	}
	return fmt.Sprintf("%s/%s", h.Kind, h.Name)
}

// Edge represents a directed, typed reference between two resources or a target hint.
type Edge struct {
	ID             string                `json:"id"`
	Type           EdgeType              `json:"type"`
	From           inventory.ResourceID  `json:"from"`
	To             *inventory.ResourceID `json:"to,omitempty"`
	ToHint         EdgeTargetHint        `json:"to_hint"`
	Location       nir.Location          `json:"location"`
	Optional       bool                  `json:"optional"`
	Status         ResolutionStatus      `json:"status"`
	SourceResource *inventory.Resource   `json:"-"`
	TargetResource *inventory.Resource   `json:"-"`
}

// Node wraps an admitted inventory resource within the relationship graph.
type Node struct {
	Resource      *inventory.Resource
	OutgoingEdges []*Edge
	IncomingEdges []*Edge
}

// Graph models the complete set of resources and their directed relationships.
type Graph struct {
	Nodes  map[string]*Node // Keyed by ResourceID.ScopeKey()
	Edges  []*Edge
	byKind map[string][]*Node
	byNS   map[string][]*Node
}

// NewGraph initializes an empty relationship graph.
func NewGraph() *Graph {
	return &Graph{
		Nodes:  make(map[string]*Node),
		Edges:  make([]*Edge, 0),
		byKind: make(map[string][]*Node),
		byNS:   make(map[string][]*Node),
	}
}
